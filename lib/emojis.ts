// Flat, order-preserving, de-duplicated list of every emoji across categories.
export const ALL_EMOJIS: string[] = (() => {
  const seen = new Set<string>();
  const flat: string[] = [];
  for (const category of EMOJI_CATEGORIES) {
    for (const emoji of category.emojis) {
      if (!seen.has(emoji)) {
        seen.add(emoji);
        flat.push(emoji);
      }
    }
  }
  return flat;
})();
